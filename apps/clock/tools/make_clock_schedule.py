"""Generate apps/clock/clock_schedule.h, the Clock app's con schedule, from a CSV.

    python3 apps/clock/tools/make_clock_schedule.py apps/clock/tools/clock_schedule.csv apps/clock/clock_schedule.h

Columns: day (Fri, Sat, Sun, ...), time (HH:MM, 24-hour, local time at the con), stage, talk. Text is reduced to
plain ASCII, the only characters the Clock's fonts have.
"""
import csv
import sys
import unicodedata

WDAY = {"Sun": 0, "Mon": 1, "Tue": 2, "Wed": 3, "Thu": 4, "Fri": 5, "Sat": 6}
SWAPS = {"‘": "'", "’": "'", "“": '"', "”": '"', "–": "-", "—": "-",
         "…": "...", " ": " "}


def ascii_text(s):
    for a, b in SWAPS.items():
        s = s.replace(a, b)
    return unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().strip()


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(src, dst):
    rows = []
    with open(src, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            day = r["day"].strip()[:3].title()
            if day not in WDAY:
                sys.exit(f"unknown day in {r}")
            h, m = (int(x) for x in r["time"].strip().split(":"))
            rows.append((WDAY[day], h, m, ascii_text(r["stage"]), ascii_text(r["talk"])))
    rows.sort()
    out = ["// Generated by tools/make_clock_schedule.py from " + src.rsplit("/", 1)[-1] + ". Do not edit.",
           "#pragma once",
           "#include <stdint.h>",
           "",
           "typedef struct {",
           "    uint8_t wday, hour, minute; // wday as in struct tm: 0 = Sunday",
           "    const char *stage, *talk;",
           "} event_t;",
           "",
           "static const event_t schedule[] = {"]
    out += [f"    {{{wd}, {h}, {m}, {c_string(st)}, {c_string(tk)}}}," for wd, h, m, st, tk in rows]
    out += ["};", "#define NEVENTS ((int)(sizeof schedule / sizeof *schedule))", ""]
    with open(dst, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {dst}: {len(rows)} events")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
