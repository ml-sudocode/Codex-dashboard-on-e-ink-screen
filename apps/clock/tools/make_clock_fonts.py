"""Generate apps/clock/clock_fonts.h, the Clock app's bitmap fonts, from DejaVu Sans (Bitstream Vera / DejaVu license).

    python3 apps/clock/tools/make_clock_fonts.py apps/clock/clock_fonts.h

Needs Pillow and the DejaVu fonts (Debian/Ubuntu: fonts-dejavu-core). Each font: one glyph height (cropped to the ink
of the whole character set), a width per glyph (also the advance), rows padded to whole bytes, MSB = leftmost pixel.
Glyphs are run-length coded: a 0x00 or 0xFF byte is followed by how many times it repeats (1-255); any other byte
stands for itself. That halves the size (most of a big glyph is blank or solid).
"""
import sys

from PIL import Image, ImageDraw, ImageFont

BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
REG = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"

FONTS = [  # C name, ttf, pixel size, first char, last char
    ("f_hour", BOLD, 72, "0", "9"),     # hour numbers on the dial
    ("f_big", BOLD, 130, " ", "~"),     # Badge text line 1
    ("f_mid", BOLD, 60, " ", "~"),      # line 2
    ("f_small", REG, 38, " ", "~"),     # lines 3+, date
    ("f_day", BOLD, 32, " ", "~"),      # "Day N", messages
    ("f_con", BOLD, 21, " ", "~"),      # con name
    ("f_label", REG, 19, " ", "~"),     # schedule labels
    ("f_labelb", BOLD, 19, " ", "~"),   # their start time
]


def rle(b):
    out, i = bytearray(), 0
    while i < len(b):
        j = i + 1
        if b[i] in (0x00, 0xFF):
            while j < len(b) and b[j] == b[i] and j - i < 255:
                j += 1
            out += bytes((b[i], j - i))
        else:
            out.append(b[i])
        i = j
    return out


biggest = 0


def build(cname, path, size, first, last):
    font = ImageFont.truetype(path, size)
    asc, desc = font.getmetrics()
    full_h = asc + desc
    chars = [chr(c) for c in range(ord(first), ord(last) + 1)]
    ims, top, bot = [], full_h, 0
    for ch in chars:
        im = Image.new("1", (max(1, round(font.getlength(ch))), full_h), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = "1"
        d.text((0, 0), ch, font=font, fill=1)
        bb = im.getbbox()
        if bb:
            top, bot = min(top, bb[1]), max(bot, bb[3])
        ims.append(im)
    global biggest
    bits, widths, offsets = bytearray(), [], []
    for im in ims:
        raw = im.crop((0, top, im.width, bot)).tobytes()
        biggest = max(biggest, len(raw))
        offsets.append(len(bits))
        widths.append(im.width)
        bits += rle(raw)
    assert max(widths) < 256
    out = [f"// {cname}: {path.rsplit('/', 1)[-1]} {size} px, '{first}'..'{last}', {bot - top} px tall",
           f"static const uint8_t {cname}_bits[] = {{"]
    out += ["    " + ",".join(f"0x{b:02X}" for b in bits[i:i + 32]) + "," for i in range(0, len(bits), 32)]
    out += ["};",
            f"static const uint8_t {cname}_w[] = {{{','.join(map(str, widths))}}};",
            f"static const uint32_t {cname}_off[] = {{{','.join(map(str, offsets))}}};",
            f"static const font_t {cname} = {{{bot - top}, {ord(first)}, {len(chars)}, {cname}_w, {cname}_off, "
            f"{cname}_bits}};", ""]
    return "\n".join(out)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    parts = ["// Generated by tools/make_clock_fonts.py from DejaVu Sans (Bitstream Vera / DejaVu license). "
             "Do not edit.",
             "#pragma once",
             "#include <stdint.h>",
             "",
             "typedef struct {",
             "    uint16_t h;               // every glyph is this tall",
             "    uint8_t first, count;     // characters first .. first + count - 1",
             "    const uint8_t *w;         // width of each glyph, px (also the advance)",
             "    const uint32_t *off;      // where each glyph starts in bits",
             "    const uint8_t *bits;      // run-length coded glyphs (see tools/make_clock_fonts.py)",
             "} font_t;",
             ""]
    parts += [build(*spec) for spec in FONTS]
    parts.insert(4, f"#define GLYPH_MAX {biggest} // bytes in the biggest glyph, unpacked\n")
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(parts))
    print("wrote", sys.argv[1])
